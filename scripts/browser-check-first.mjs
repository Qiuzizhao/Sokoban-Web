import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { parseLevel,solveSokoban } from 'miaoda-game-sokoban-core';
import { levels } from '../web/levels.js';

const directory=fs.mkdtempSync(path.join(os.tmpdir(),'sokoban-first-'));
const file=path.join(directory,'game.html');
fs.copyFileSync('推箱子第一关.html',file);
const url=pathToFileURL(file).href;
const browser=await chromium.launch({headless:true,executablePath:'C:/Users/Qiuzizhao/AppData/Local/ms-playwright/chromium-1148/chrome-win/chrome.exe'});
try{
  const context=await browser.newContext({offline:true,viewport:{width:1024,height:768}});
  const page=await context.newPage(),errors=[],requests=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=>{if(request.url()!==url&&!request.url().startsWith('data:'))requests.push(request.url());});
  await page.addInitScript(()=>localStorage.setItem('sokoban-web-v1','full-version-sentinel'));
  await page.goto(url);
  await page.locator('.crate').first().waitFor();
  assert.equal(await page.locator('.level-cell').count(),1);
  assert.equal(await page.locator('#catalog-toggle').isVisible(),false);
  assert.equal(await page.locator('.level-navigation').isVisible(),false);
  assert.equal(await page.locator('#catalog').isVisible(),false);
  assert.equal(await page.locator('#next').isDisabled(),true);
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.locator('#moves').textContent(),'1');
  await page.locator('#undo').click();assert.equal(await page.locator('#moves').textContent(),'0');
  await page.locator('#redo').click();assert.equal(await page.locator('#moves').textContent(),'1');
  await page.locator('#restart').click();
  const solution=solveSokoban(parseLevel(levels[0].xsb).level,{maxNodes:50000});
  const keys={up:'ArrowUp',down:'ArrowDown',left:'ArrowLeft',right:'ArrowRight'};
  for(const direction of solution.directions)await page.keyboard.press(keys[direction]);
  assert.equal(await page.locator('#success-next').textContent(),'再玩一次 ');
  assert.equal(await page.locator('#success').evaluate(dialog=>dialog.open),true);
  await page.getByRole('button',{name:'再玩一次'}).click();
  assert.equal(await page.locator('#level-number').textContent(),'01');
  assert.equal(await page.locator('#moves').textContent(),'0');
  assert.equal(await page.locator('#success').evaluate(dialog=>dialog.open),false);
  await page.keyboard.press('ArrowRight');
  await page.waitForTimeout(250);
  await page.reload();
  assert.equal(await page.locator('#moves').textContent(),'1');
  assert.equal(await page.evaluate(()=>localStorage.getItem('sokoban-web-v1')),'full-version-sentinel');
  assert.equal(await page.evaluate(()=>Array.from(document.images).every(image=>image.complete&&image.naturalWidth>0)),true);
  await page.locator('#restart').click();
  await page.setViewportSize({width:320,height:640});
  const button=await page.locator('[data-direction="right"]').boundingBox();
  const map=await page.locator('#board').boundingBox();
  assert.ok(button.width>=60&&button.y+button.height<=640);
  assert.ok(map.width>=272);
  fs.mkdirSync('qa',{recursive:true});
  await page.screenshot({path:'qa/first-level-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);assert.deepEqual(requests,[]);
  console.log('First-level-only HTML passed: isolated offline file, one level, no selection/next, victory/replay, undo/redo, independent save, mobile layout, images and zero external requests.');
}finally{await browser.close();}
